#!/usr/bin/env python3
"""Writes public/auth/theme.css: the light palette (the app's original colours) and a dark palette for every colour variable
used in public/*.html|js (var(--bg-xxxxxx), var(--tx-xxxxxx), var(--bd-xxxxxx): background, text/fill, border).
   python3 scripts/make-theme.py"""
import re, glob, colorsys, os
root = os.path.join(os.path.dirname(__file__), "..", "public")
used = set()
for f in glob.glob(os.path.join(root, "*.html")) + glob.glob(os.path.join(root, "*.js")):
    for ns, hx in re.findall(r"var\(--(bg|tx|bd)-([0-9a-f]{3,6})\)", open(f).read()): used.add((ns, hx))
for ns, hx in (("bd", "adb5bd"), ("bd", "dee2e6"), ("bd", "e9ecef"), ("tx", "6c757d"), ("tx", "adb5bd")): used.add((ns, hx))   # chart classes
def full(hx): return hx if len(hx) == 6 else "".join(c * 2 for c in hx)
def hls(hx): r, g, b = (int(full(hx)[i:i + 2], 16) / 255 for i in (0, 2, 4)); h, l, s = colorsys.rgb_to_hls(r, g, b); return h, l, s
def hexof(h, l, s): r, g, b = colorsys.hls_to_rgb(h, max(0, min(1, l)), max(0, min(1, s))); return "%02x%02x%02x" % (round(r * 255), round(g * 255), round(b * 255))
# hand-picked greys (the app's neutral scale) -> dark equivalents
BG = {"fff": "161b22", "f8f9fa": "1c222a", "f1f3f5": "1c222a", "e9ecef": "232b34", "dee2e6": "2a323c", "ced4da": "343d48", "eee": "1c222a", "343a40": "46505c", "6c757d": "4b5563", "adb5bd": "59626d", "212529": "2d333b"}
TX = {"212529": "e6edf3", "343a40": "d4dbe3", "495057": "b8c2cc", "6c757d": "9ba7b4", "868e96": "8b97a3", "adb5bd": "76808b", "666": "9ba7b4", "aaa": "8b97a3", "ced4da": "c0c9d2", "eee": "d0d7de", "f8f9fa": "f0f3f6"}
BD = {"ced4da": "3a424c", "dee2e6": "30363d", "e9ecef": "2a313a", "eee": "2a313a", "f1f3f5": "242b33", "adb5bd": "59626d", "aaa": "59626d", "ccc": "3a424c", "fff": "30363d", "343a40": "59626d"}
def dark(ns, hx):
    if hx in {"bg": BG, "tx": TX, "bd": BD}[ns]: return {"bg": BG, "tx": TX, "bd": BD}[ns][hx]
    h, l, s = hls(hx)
    if ns == "bg":
        if s > 0.5 and 0.25 < l < 0.7: return hx                      # an accent (button, bar): same in both themes
        return hexof(h, 0.11 + (1 - l) * 0.5, min(s, 0.6))             # a tinted panel (info, warning, ok): dark version of the same tint
    if ns == "tx":
        if l > 0.88 and s < 0.3: return hx                            # white text on a button stays white
        return hexof(h, 0.58 + (1 - l) * 0.15, min(1, s * 0.95))       # coloured text: lighter, same hue
    if s > 0.4 and 0.2 < l < 0.7: return hx                            # an accent line stays
    return hexof(h, 0.15 + (1 - l) * 0.4, min(s, 0.55))                 # a tinted border
light = "\n".join(f"  --{ns}-{hx}: #{full(hx) if len(hx) == 3 and False else hx};" for ns, hx in sorted(used))
dk = "\n".join(f"  --{ns}-{hx}: #{dark(ns, hx)};" for ns, hx in sorted(used))
css = f"""/* Light and dark colours of Dive Manager (generated by scripts/make-theme.py: do not edit by hand).
   Every colour in the app is a variable named --bg-/--tx-/--bd- plus its light-mode hex; the dark theme redefines them. */
:root {{
{light}
}}
html[data-theme="dark"] {{
  color-scheme: dark;
  --bg: #0d1117; --text: #e6edf3; --green: #3fb950; --red: #f85149; --yellow: #d29922;
{dk}
}}
html[data-theme="light"] {{ color-scheme: light; }}
/* things that are not plain colours */
html[data-theme="dark"] .leaflet-tile-pane {{ filter: invert(1) hue-rotate(180deg) brightness(.92) contrast(.9) saturate(.8); }}
html[data-theme="dark"] .leaflet-container {{ background: #1b2430; }}
html[data-theme="dark"] .leaflet-popup-content-wrapper, html[data-theme="dark"] .leaflet-popup-tip, html[data-theme="dark"] .leaflet-bar a {{ background: #1c222a; color: #e6edf3; }}
html[data-theme="dark"] .leaflet-bar a {{ border-bottom-color: #30363d; }}
html[data-theme="dark"] .leaflet-control-attribution {{ background: rgba(13,17,23,.8) !important; color: #9ba7b4; }}
html[data-theme="dark"] .leaflet-control-attribution a {{ color: #74c0fc; }}
html[data-theme="dark"] input, html[data-theme="dark"] select, html[data-theme="dark"] textarea {{ background-color: var(--bg-fff); color: var(--text); }}
html[data-theme="dark"] .map-note {{ background: rgba(57,47,14,.95); }}
html[data-theme="dark"] ::placeholder {{ color: #6e7781; opacity: 1; }}
html[data-theme="dark"] a:not(.btn-main) {{ color: #74c0fc; }}
html[data-theme="dark"] img.preview {{ background: #fff; }}
"""
open(os.path.join(root, "auth", "theme.css"), "w").write(css)
print("theme.css:", len(used), "colours,", len(css), "bytes")
