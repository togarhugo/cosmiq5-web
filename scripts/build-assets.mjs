// Bundles ./public into src/assets.generated.js so the Worker can serve the app itself.
// (Avoids the Workers Assets upload API; the whole app is ~100 KB, far below the free 3 MB limit.)
import fs from "node:fs"; import path from "node:path";
const version = JSON.parse(fs.readFileSync("package.json", "utf8")).version;
// One source of truth for the version: package.json -> Worker, UI and offline cache.
fs.writeFileSync("src/version.js", `// generated by scripts/build-assets.mjs - do not edit\nexport const VERSION = ${JSON.stringify(version)};\n`);
fs.writeFileSync("public/version.js", `self.APP_VERSION = ${JSON.stringify(version)};\n`);
const dir = path.resolve("public");
const types = { ".html": "text/html; charset=utf-8", ".js": "text/javascript; charset=utf-8", ".webmanifest": "application/manifest+json", ".png": "image/png", ".json": "application/json" };
const out = {};
(function walk(d, prefix) {
  for (const f of fs.readdirSync(d, { withFileTypes: true })) {
    if (f.isDirectory()) { walk(path.join(d, f.name), prefix + f.name + "/"); continue; }
    const t = types[path.extname(f.name)];
    if (!t) continue;
    let buf = fs.readFileSync(path.join(d, f.name));
    if (prefix === "auth/" && f.name.endsWith(".html")) buf = Buffer.from(buf.toString("utf8").replaceAll("__APP_VERSION__", version));
    out["/" + prefix + f.name] = { t, b: buf.toString("base64") };
  }
})(dir, "");
fs.writeFileSync("src/assets.generated.js", "// generated by scripts/build-assets.mjs - do not edit\nexport default " + JSON.stringify(out) + ";\n");
console.log("version", version + ";", "bundled", Object.keys(out).length, "files,", Math.round(JSON.stringify(out).length / 1024), "KB");
